import { SubtitleCue } from '../types';

export function formatTimeSrt(seconds: number): string {
  const pad = (num: number, size = 2) => String(Math.floor(num)).padStart(size, '0');
  const hrs = pad(seconds / 3600);
  const mins = pad((seconds % 3600) / 60);
  const secs = pad(seconds % 60);
  const ms = pad(Math.floor((seconds % 1) * 1000), 3);
  return `${hrs}:${mins}:${secs},${ms}`;
}

export function formatTimeVtt(seconds: number): string {
  const pad = (num: number, size = 2) => String(Math.floor(num)).padStart(size, '0');
  const hrs = pad(seconds / 3600);
  const mins = pad((seconds % 3600) / 60);
  const secs = pad(seconds % 60);
  const ms = pad(Math.floor((seconds % 1) * 1000), 3);
  return `${hrs}:${mins}:${secs}.${ms}`;
}

export function formatPlayerTime(seconds: number): string {
  if (isNaN(seconds) || seconds < 0) return '00:00';
  const mins = Math.floor(seconds / 60);
  const secs = Math.floor(seconds % 60);
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${pad(mins)}:${pad(secs)}`;
}

export function generateSrt(cues: SubtitleCue[]): string {
  return cues
    .map((cue, index) => {
      const idx = index + 1;
      const start = formatTimeSrt(cue.startTime);
      const end = formatTimeSrt(cue.endTime);
      const speakerPrefix = cue.speaker ? `[${cue.speaker}]: ` : '';
      return `${idx}\n${start} --> ${end}\n${speakerPrefix}${cue.text.trim()}\n`;
    })
    .join('\n');
}

export function generateVtt(cues: SubtitleCue[]): string {
  const header = 'WEBVTT - Generated by SubFlow AI\n\n';
  const body = cues
    .map((cue, index) => {
      const start = formatTimeVtt(cue.startTime);
      const end = formatTimeVtt(cue.endTime);
      const speakerPrefix = cue.speaker ? `<v ${cue.speaker}>` : '';
      return `${index + 1}\n${start} --> ${end}\n${speakerPrefix}${cue.text.trim()}\n`;
    })
    .join('\n');
  return header + body;
}

export function generateTxt(cues: SubtitleCue[]): string {
  return cues
    .map(cue => {
      const speaker = cue.speaker ? `${cue.speaker}: ` : '';
      return `${speaker}${cue.text.trim()}`;
    })
    .join(' ');
}

export function downloadFile(content: string, filename: string, mimeType: string = 'text/plain') {
  const blob = new Blob([content], { type: `${mimeType};charset=utf-8;` });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', filename);
  link.style.visibility = 'hidden';
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
